#!/usr/bin/env python3
"""Plot the iteration history of a positive-constrained magnetic inversion.

The script reads the two ASCII files generated by
``run_magnetic_inversion_positive_noisy.py``:

* inversion_history_positive.dat
* inversion_model_history_positive.dat

It creates:

* inversion_convergence_positive.png: scalar convergence diagnostics;
* inversion_model_evolution_positive.png: susceptibility evolution by cell
  and iteration;
* inversion_model_statistics_positive.png: minimum, maximum, mean and
  standard deviation of susceptibility at each saved iteration.

Run from the repository root, for example:

    python examples/magnetic/noisy/plot_magnetic_inversion_history_positive.py \
        --noise-level 3

Coordinates use x = East, y = North and z positive downward.

Boukar Abdelghafour  GeoInvLab3D   MIT License Copyright (c) 2026
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np


SCRIPT_DIR = Path(__file__).resolve().parent
RESULTS_ROOT = SCRIPT_DIR / "inversion_results"


HISTORY_COLUMNS = (
    "iteration",
    "data_rms",
    "normalized_rms",
    "phi_d",
    "phi_m",
    "phi",
    "model_min",
    "model_max",
    "elapsed_s",
)

MODEL_HISTORY_COLUMNS = (
    "iteration",
    "cell_index",
    "x_center_m",
    "y_center_m",
    "z_center_m",
    "susceptibility_SI",
)


def load_ascii_table(path: Path, expected_columns: int) -> np.ndarray:
    """Load a whitespace-delimited ASCII table, ignoring comment lines."""

    if not path.is_file():
        raise FileNotFoundError(
            f"Required history file was not found: {path}\n"
            "Run the positive-constrained magnetic inversion first."
        )

    try:
        table = np.loadtxt(path, comments="#", dtype=float, ndmin=2)
    except ValueError as exc:
        raise ValueError(
            f"Could not parse history file: {path}\n{exc}"
        ) from exc

    if table.size == 0 or table.shape[1] != expected_columns:
        raise ValueError(
            f"Unexpected table shape in {path}: {table.shape}. "
            f"Expected {expected_columns} columns."
        )

    if not np.all(np.isfinite(table)):
        raise ValueError(f"History file contains NaN or infinite values: {path}")

    return table


def plot_convergence(history: np.ndarray, output_path: Path) -> None:
    """Plot scalar data-fit, objective and model-bound diagnostics."""

    iteration = history[:, 0]

    fig, axes = plt.subplots(
        2,
        2,
        figsize=(12.5, 8.0),
        constrained_layout=True,
    )

    ax = axes[0, 0]
    ax.plot(iteration, history[:, 1], marker="o", markersize=3)
    ax.set_title("Data RMS")
    ax.set_xlabel("Iteration")
    ax.set_ylabel("Data RMS")
    ax.grid(True, alpha=0.3)

    ax = axes[0, 1]
    ax.plot(iteration, history[:, 2], marker="o", markersize=3)
    ax.set_title("Normalized data RMS")
    ax.set_xlabel("Iteration")
    ax.set_ylabel("Normalized RMS")
    ax.grid(True, alpha=0.3)

    ax = axes[1, 0]
    ax.plot(iteration, history[:, 3], marker="o", markersize=3, label=r"$\Phi_d$")
    ax.plot(iteration, history[:, 4], marker="s", markersize=3, label=r"$\Phi_m$")
    ax.plot(iteration, history[:, 5], marker="^", markersize=3, label=r"$\Phi$")
    ax.set_title("Objective-function components")
    ax.set_xlabel("Iteration")
    ax.set_ylabel("Objective value")
    ax.set_yscale("symlog", linthresh=1.0e-12)
    ax.legend()
    ax.grid(True, alpha=0.3)

    ax = axes[1, 1]
    ax.plot(iteration, history[:, 6], marker="o", markersize=3, label="Minimum")
    ax.plot(iteration, history[:, 7], marker="s", markersize=3, label="Maximum")
    ax.set_title("Susceptibility bounds")
    ax.set_xlabel("Iteration")
    ax.set_ylabel("Susceptibility (SI)")
    ax.legend()
    ax.grid(True, alpha=0.3)

    fig.suptitle("Positive-constrained magnetic inversion: convergence history")
    fig.savefig(output_path, dpi=300, bbox_inches="tight")
    plt.close(fig)


def prepare_model_matrix(model_history: np.ndarray):
    """Return iterations, cell indices, and a (cell, iteration) model matrix."""

    iterations = np.unique(model_history[:, 0].astype(int))
    cell_indices = np.unique(model_history[:, 1].astype(int))

    expected_rows = iterations.size * cell_indices.size
    if model_history.shape[0] != expected_rows:
        raise ValueError(
            "The model-history file does not contain exactly one value for "
            "every cell at every saved iteration. Check whether the file is "
            "complete and whether an inversion was interrupted."
        )

    if not np.array_equal(cell_indices, np.arange(cell_indices.size)):
        raise ValueError("Cell indices must be consecutive and start at zero.")

    matrix = np.full((cell_indices.size, iterations.size), np.nan, dtype=float)

    iteration_lookup = {value: index for index, value in enumerate(iterations)}
    for row in model_history:
        it = int(row[0])
        cell = int(row[1])
        matrix[cell, iteration_lookup[it]] = row[5]

    if not np.all(np.isfinite(matrix)):
        raise ValueError("The model-history table has missing cell/iteration values.")

    return iterations, cell_indices, matrix


def plot_model_evolution(
    model_history: np.ndarray,
    output_path: Path,
) -> tuple[np.ndarray, np.ndarray]:
    """Plot the evolution of susceptibility for all model cells."""

    iterations, cell_indices, matrix = prepare_model_matrix(model_history)

    fig, ax = plt.subplots(figsize=(11.5, 6.5), constrained_layout=True)
    image = ax.imshow(
        matrix,
        origin="lower",
        aspect="auto",
        interpolation="nearest",
        extent=(
            iterations[0] - 0.5,
            iterations[-1] + 0.5,
            cell_indices[0] - 0.5,
            cell_indices[-1] + 0.5,
        ),
    )
    ax.set_title("Susceptibility model evolution")
    ax.set_xlabel("Iteration")
    ax.set_ylabel("Cell index (zero-based)")
    colorbar = fig.colorbar(image, ax=ax)
    colorbar.set_label("Magnetic susceptibility (SI)")
    fig.savefig(output_path, dpi=300, bbox_inches="tight")
    plt.close(fig)

    return iterations, matrix


def plot_model_statistics(
    iterations: np.ndarray,
    matrix: np.ndarray,
    output_path: Path,
) -> None:
    """Plot summary statistics of the model at each saved iteration."""

    minimum = np.min(matrix, axis=0)
    maximum = np.max(matrix, axis=0)
    mean = np.mean(matrix, axis=0)
    standard_deviation = np.std(matrix, axis=0)

    fig, axes = plt.subplots(
        1,
        2,
        figsize=(12.0, 4.8),
        constrained_layout=True,
    )

    axes[0].plot(iterations, minimum, marker="o", markersize=3, label="Minimum")
    axes[0].plot(iterations, mean, marker="s", markersize=3, label="Mean")
    axes[0].plot(iterations, maximum, marker="^", markersize=3, label="Maximum")
    axes[0].set_title("Susceptibility range and mean")
    axes[0].set_xlabel("Iteration")
    axes[0].set_ylabel("Susceptibility (SI)")
    axes[0].legend()
    axes[0].grid(True, alpha=0.3)

    axes[1].plot(
        iterations,
        standard_deviation,
        marker="o",
        markersize=3,
    )
    axes[1].set_title("Model standard deviation")
    axes[1].set_xlabel("Iteration")
    axes[1].set_ylabel("Standard deviation (SI)")
    axes[1].grid(True, alpha=0.3)

    fig.suptitle("Positive-constrained magnetic inversion: model statistics")
    fig.savefig(output_path, dpi=300, bbox_inches="tight")
    plt.close(fig)


def parse_arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Plot scalar and model-parameter histories from a "
            "positive-constrained magnetic inversion."
        )
    )
    parser.add_argument(
        "--noise-level",
        type=int,
        choices=(1, 3, 5),
        default=3,
        help="Noise percentage used for the inversion (default: 3).",
    )
    parser.add_argument(
        "--results-dir",
        type=Path,
        default=None,
        help="Optional explicit directory containing the history files.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_arguments()

    results_dir = (
        args.results_dir
        if args.results_dir is not None
        else RESULTS_ROOT / f"noise_{args.noise_level}pct"
    )
    results_dir = results_dir.expanduser().resolve()

    scalar_history_file = results_dir / "inversion_history_positive.dat"
    model_history_file = results_dir / "inversion_model_history_positive.dat"

    scalar_history = load_ascii_table(
        scalar_history_file,
        expected_columns=len(HISTORY_COLUMNS),
    )
    model_history = load_ascii_table(
        model_history_file,
        expected_columns=len(MODEL_HISTORY_COLUMNS),
    )

    convergence_figure = results_dir / "inversion_convergence_positive.png"
    evolution_figure = results_dir / "inversion_model_evolution_positive.png"
    statistics_figure = results_dir / "inversion_model_statistics_positive.png"

    plot_convergence(scalar_history, convergence_figure)
    iterations, model_matrix = plot_model_evolution(
        model_history,
        evolution_figure,
    )
    plot_model_statistics(
        iterations,
        model_matrix,
        statistics_figure,
    )

    print("=" * 72)
    print("GeoInvLab3D - POSITIVE-CONSTRAINED MAGNETIC INVERSION HISTORY")
    print("=" * 72)
    print(f"Results directory : {results_dir}")
    print(f"Saved iterations : {iterations.size}")
    print(f"Model cells       : {model_matrix.shape[0]}")
    print("Generated figures:")
    print(f"  - {convergence_figure.name}")
    print(f"  - {evolution_figure.name}")
    print(f"  - {statistics_figure.name}")


if __name__ == "__main__":
    main()
